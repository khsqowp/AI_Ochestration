export const PASSAGE_SOURCE = 'original-practice-copy-2026-10'
export const PASSAGES = Object.freeze([
  ...english.map((text, i) => Object.freeze({ id: `en-${String(i + 1).padStart(3, '0')}`, locale: 'en', text })),
  ...korean.map((text, i) => Object.freeze({ id: `ko-${String(i + 1).padStart(3, '0')}`, locale: 'ko', text }))
])
export function pickPassage(locale = 'en', random = Math.random) {
  const options = PASSAGES.filter(passage => passage.locale === locale)
  if (!options.length) throw new Error('Unsupported passage locale')
  return options[Math.floor(random() * options.length)]
}
